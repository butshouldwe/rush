import fs from 'node:fs';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import type { Finding, Rollup } from './types.js';

/** Markdown only: fold each line break and replace NUL. JSON keeps the input. */
function displayText(text: string): string {
  return text.replace(/\r\n|\r|\n/g, ' ').replaceAll('\0', '\uFFFD');
}

/** Prevent syntax before GFM tokenizes. Entities also break bare autolinks
 * and keep boundary whitespace from being trimmed by the block parser. */
function markdownText(text: string): string {
  return displayText(text).replace(/^ +| +$|[^\S ]|[!-/:-@[-`{-~]/g, (part) =>
    part === '|' ? '\\|' : Array.from(part, (ch) => `&#${ch.charCodeAt(0)};`).join(''),
  );
}

function markdownCode(text: string, tableCell = false): string {
  const display = displayText(text);
  if (display === '') return '';
  // GFM strips a backslash before a pipe during cell splitting, even inside
  // a code span. Use literal text when the backslash is part of the value.
  if (tableCell && display.includes('\\|')) return markdownText(display);

  let width = 1;
  for (const [run] of display.matchAll(/`+/g)) width = Math.max(width, run.length + 1);
  const fence = '`'.repeat(width);
  const body = tableCell ? display.replaceAll('|', '\\|') : display;
  // GFM removes one padding space from each end unless the body is all
  // spaces. Padding separates edge backticks and preserves edge spaces.
  const pad = /(?:^[` ]|[` ]$)/.test(body) && /[^ ]/.test(body) ? ' ' : '';
  return `${fence}${pad}${body}${pad}${fence}`;
}

/**
 * Filesystem-safe file base for a project name. Scoped names (`@scope/name`)
 * flatten to a single segment (`@scope__name`) so `projects/` stays a flat,
 * globbable directory. Anything that would escape the output directory is
 * rejected outright.
 *
 * Deliberately mirrors @butshouldwe/sbom-rush's `scenarioFileBase`
 * (src/run.ts) rather than importing it: the extraction contract for both
 * plugins is zero workspace imports (see rushRepo.ts's mirror comment).
 * Keep the two policy-identical if either sanitizer changes.
 */
export function projectFileBase(projectName: string): string {
  const base = projectName.replaceAll('/', '__').replaceAll('\\', '__');
  if (base.length === 0 || base === '.' || base.includes('..') || path.isAbsolute(base)) {
    throw new Error(`project name "${projectName}" cannot be used as a report file name`);
  }
  return base;
}

function findingTable(findings: Finding[]): string {
  if (findings.length === 0) return '_No findings._\n';
  const rows = findings.map(
    (f) =>
      `| ${markdownText(f.type)} | ${markdownCode(f.path, true)} | ${markdownText(f.detail)} | ${markdownText(f.source)} |`,
  );
  return ['| Type | Where | Detail | Pass |', '|---|---|---|---|', ...rows, ''].join('\n');
}

export function monorepoMarkdown(rollup: Rollup): string {
  const lines: string[] = [
    `# Fallow rollup: monorepo`,
    '',
    `- Generated by ${markdownText(rollup.generator)} (fallow ${markdownText(rollup.fallowVersion)}) at ${markdownText(rollup.generatedAt)}`,
    `- Git: ${markdownCode(rollup.gitSha)}${rollup.changedSince ? ` · changed since ${markdownCode(rollup.changedSince)}` : ''}`,
    ...(rollup.projectsFilter
      ? [
          `- **Narrowed to project(s): ${rollup.projectsFilter.map((project) => markdownCode(project)).join(', ')}** — not a full-repo view`,
        ]
      : []),
    `- Attributed findings: **${rollup.monorepo.totalFindings}**`,
    '',
    '## Findings by type',
    '',
    ...(Object.keys(rollup.monorepo.byType).length === 0
      ? ['_None._']
      : Object.entries(rollup.monorepo.byType).map(
          ([type, count]) => `- ${markdownText(type)}: ${count}`,
        )),
    '',
    '## Findings by project',
    '',
    '| Project | Findings |',
    '|---|---|',
    ...rollup.projects.map((p) => `| ${markdownText(p.project)} | ${p.findings.length} |`),
    '',
  ];

  if (Object.keys(rollup.monorepo.dupes).length > 0) {
    lines.push('## Duplication (monorepo-wide)', '');
    lines.push(
      ...Object.entries(rollup.monorepo.dupes).map(
        ([key, count]) => `- ${markdownText(key)}: ${count}`,
      ),
      '',
    );
  }
  if (Object.keys(rollup.monorepo.health).length > 0) {
    lines.push('## Health (monorepo-wide)', '');
    lines.push(
      ...Object.entries(rollup.monorepo.health).map(
        ([key, count]) => `- ${markdownText(key)}: ${count}`,
      ),
      '',
    );
  }
  if (rollup.monorepo.unsupported.length > 0) {
    lines.push('## Unsupported Fallow categories', '');
    lines.push(
      ...rollup.monorepo.unsupported.map(
        ({ category, count }) => `- ${markdownText(category)}: ${count}`,
      ),
      '',
    );
  }
  if (rollup.monorepo.rushPlumbing.length > 0) {
    lines.push(
      '## Rush plumbing (excluded from project rollups)',
      '',
      findingTable(rollup.monorepo.rushPlumbing),
    );
  }
  if (rollup.monorepo.unattributed.length > 0) {
    lines.push('## Unattributed paths', '', findingTable(rollup.monorepo.unattributed));
  }
  return `${lines.join('\n')}\n`;
}

export function projectMarkdown(rollup: Rollup, projectName: string): string {
  const project = rollup.projects.find((p) => p.project === projectName);
  if (!project) throw new Error(`unknown project ${projectName}`);
  return [
    `# Fallow rollup: ${markdownText(project.project)}`,
    '',
    `- Folder: ${markdownCode(project.projectFolder)}`,
    `- Findings: **${project.findings.length}**`,
    '',
    findingTable(project.findings),
  ].join('\n');
}

/**
 * Thrown when a scoped run would silently overwrite a report generated for a
 * different scope (issue #5). Distinguished from other `writeReports`
 * failures because the CLI maps it to exit 2 (usage/config error - the user
 * needs to choose a different `--out` or clean up) rather than exit 1
 * (runtime failure).
 */
export class ScopeConflictError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'ScopeConflictError';
  }
}

/**
 * Implicit destinations with the conventional common/temp/fallow-rush suffix
 * must have no symlink from their Rush root through the report directory.
 * Missing directories are accepted; dangling and internal links are refused.
 * Only ENOENT means absent. Return the lexical absolute spelling for ALL
 * subsequent writer operations; never write through the original argument.
 * This check never writes or resolves links away.
 * Other API destinations are caller-selected, as are explicitOut destinations.
 * Concurrent replacement is outside the checkout-content threat model.
 */
export function guardDefaultReportDir(reportDir: string): string {
  const resolved = path.resolve(reportDir);
  const rushRoot = path.resolve(resolved, '../../..');
  if (resolved !== path.join(rushRoot, 'common', 'temp', 'fallow-rush')) return resolved;
  let component = rushRoot;
  for (const segment of ['', 'common', 'temp', 'fallow-rush']) {
    component = path.join(component, segment);
    let stat: fs.Stats;
    try {
      stat = fs.lstatSync(component);
    } catch (error) {
      if (error instanceof Error && 'code' in error && error.code === 'ENOENT') continue;
      throw error;
    }
    if (stat.isSymbolicLink()) {
      throw new Error(`refusing default report path: symlink component "${component}"`);
    }
  }
  return resolved;
}

export interface WriteReportsOptions {
  /** True when the user passed `--out`/`--report` explicitly, rather than
   * writing to the tool's default report directory. An explicit destination
   * is the escape hatch from the scope-clobber guard below: the user chose
   * this path on purpose. */
  explicitOut?: boolean;
}

function describeScope(filter: string[] | null | 'corrupt'): string {
  if (filter === 'corrupt') return 'unreadable (existing monorepo.json did not parse)';
  return filter === null ? 'the full repo (unscoped)' : `project(s) ${filter.join(', ')}`;
}

function scopesEqual(a: string[] | null, b: string[] | null): boolean {
  if (a === null || b === null) return a === b;
  return a.length === b.length && a.every((v, i) => v === b[i]);
}

/** Tolerant read of a previous run's recorded project scope. A missing file
 * reads as `'absent'` (nothing recorded yet - never a conflict, distinct from
 * a *present* report whose own `projectsFilter` happens to be `null`, i.e. it
 * was itself a full run); a present-but-unparseable file reads as
 * `'corrupt'`, which the caller must treat as "definitely differs" (fail
 * safe rather than risk silently dropping a foreign report). */
function readExistingProjectsFilter(
  monorepoJsonFile: string,
): string[] | null | 'corrupt' | 'absent' {
  if (!fs.existsSync(monorepoJsonFile)) return 'absent';
  try {
    const parsed = JSON.parse(fs.readFileSync(monorepoJsonFile, 'utf8')) as Partial<Rollup>;
    const filter = parsed.projectsFilter;
    if (filter === null || filter === undefined) return null;
    if (Array.isArray(filter) && filter.every((v) => typeof v === 'string')) return filter;
    return 'corrupt';
  } catch {
    return 'corrupt';
  }
}

/**
 * Guard against issue #5: a **scoped** run (`--project` and/or
 * `--changed-since`) that would land on top of a report recorded for a
 * *different* project scope refuses outright, rather than silently dropping
 * the other scope's projects when `projects/` is rebuilt. The comparison is
 * on `projectsFilter` specifically - that's the field whose change actually
 * causes files to disappear from `projects/`; a bare `--changed-since` run
 * against an already-full (or already-matching) report is not a conflict.
 *
 * Unscoped (full) runs always proceed - a full snapshot supersedes anything
 * that was there before. An explicit `--out`/`--report` is also always
 * exempt: the user picked this destination on purpose.
 */
function guardScopeConflict(rollup: Rollup, reportDir: string, options: WriteReportsOptions): void {
  if (options.explicitOut) return;
  const isScopedRun = rollup.projectsFilter !== null || rollup.changedSince !== null;
  if (!isScopedRun) return;

  const existing = readExistingProjectsFilter(path.join(reportDir, 'monorepo.json'));
  if (existing === 'absent') return; // nothing recorded yet — nothing to conflict with
  const differs = existing === 'corrupt' || !scopesEqual(existing, rollup.projectsFilter);
  if (!differs) return;

  throw new ScopeConflictError(
    `refusing to overwrite "${reportDir}": the existing report was generated for ${describeScope(existing)}, ` +
      `but this run is scoped to ${describeScope(rollup.projectsFilter)}. Rebuilding "projects/" here would ` +
      `silently drop the other scope's project files. Pass --out <fresh-dir> for this run, or delete ` +
      `"${reportDir}" first if you intend to replace it.`,
  );
}

/**
 * Guard against deleting files this tool does not own. `writeReports`
 * rebuilds `projects/` from scratch on every run; that's only safe when the
 * directory has a valid ownership record in `monorepo.json` or `projects/`
 * is empty/absent. Anything else - a `projects/` directory that
 * predates this tool, or `--out` pointed at an unrelated folder that happens
 * to have a `projects/` subfolder - refuses instead of recursively deleting
 * foreign files.
 */
// Must match rollup.ts's generator value: the ownership record in
// monorepo.json is only trusted when it carries this exact identity.
const PLUGIN_GENERATOR = '@butshouldwe/fallow-rush';

function guardForeignProjectsDir(reportDir: string): void {
  const projectsDir = path.join(reportDir, 'projects');
  if (!fs.existsSync(projectsDir)) return; // nothing to protect
  if (fs.readdirSync(projectsDir).length === 0) return; // empty
  const ownershipFile = path.join(reportDir, 'monorepo.json');
  let owned = false;
  try {
    if (fs.lstatSync(ownershipFile).isFile()) {
      const parsed = JSON.parse(fs.readFileSync(ownershipFile, 'utf8')) as Partial<Rollup>;
      owned =
        parsed.generator === PLUGIN_GENERATOR &&
        typeof parsed.fallowVersion === 'string' &&
        parsed.monorepo !== null &&
        typeof parsed.monorepo === 'object' &&
        !Array.isArray(parsed.monorepo);
    }
  } catch {
    // Missing, unreadable, and malformed ownership records are all foreign.
  }
  if (owned) return;
  throw new Error(
    `refusing to delete "${projectsDir}": "${ownershipFile}" is not a valid regular-file ownership record ` +
      `and the directory is not empty. fallow-rush only rebuilds tool-owned report directories. Point --out ` +
      `at a fresh directory, or remove "${projectsDir}" yourself first if it is safe to delete.`,
  );
}

/** Atomic write (temp + rename): concurrent runs never interleave torn JSON.
 * Mirrors @butshouldwe/sbom-rush's `writeFileAtomic` (src/run.ts) - copied,
 * not imported, per the zero-workspace-imports contract; keep the two shapes
 * identical if either changes. */
function writeFileAtomic(file: string, content: string): void {
  const dir = path.dirname(file);
  const tmp = path.join(
    dir,
    `.${path.basename(file)}.${process.pid}.${randomBytes(6).toString('hex')}.tmp`,
  );
  let fd: number | undefined;
  try {
    fd = fs.openSync(
      tmp,
      fs.constants.O_WRONLY | fs.constants.O_CREAT | fs.constants.O_EXCL,
      0o600,
    );
    fs.writeSync(fd, content);
    fs.closeSync(fd);
    fd = undefined;
    fs.renameSync(tmp, file);
  } catch (err) {
    if (fd !== undefined) {
      try {
        fs.closeSync(fd);
      } catch {
        /* closed */
      }
    }
    try {
      fs.unlinkSync(tmp);
    } catch {
      /* not created */
    }
    throw err;
  }
}

export function assertNoReportCollisions(projectNames: string[]): void {
  const destinations = new Map<string, { base: string; projects: string[] }>();
  for (const projectName of projectNames) {
    const base = projectFileBase(projectName);
    const key = base.toLowerCase();
    const destination = destinations.get(key) ?? { base, projects: [] };
    destination.projects.push(projectName);
    destinations.set(key, destination);
  }
  const collisions = [...destinations.entries()].filter(([, value]) => value.projects.length > 1);
  if (collisions.length === 0) return;
  throw new Error(
    `project report file name collision: ${collisions
      .map(
        ([key, value]) =>
          `shared base "${value.base}" (case-insensitive "${key}") for ${value.projects.map((name) => `"${name}"`).join(', ')}`,
      )
      .join('; ')}`,
  );
}

function errorCode(error: unknown): string | undefined {
  return error instanceof Error && 'code' in error ? String(error.code) : undefined;
}

function lockPid(lockFile: string): number | undefined {
  try {
    const parsed = JSON.parse(fs.readFileSync(lockFile, 'utf8')) as {
      pid?: unknown;
    };
    return typeof parsed.pid === 'number' && Number.isSafeInteger(parsed.pid) && parsed.pid > 0
      ? parsed.pid
      : undefined;
  } catch {
    return undefined;
  }
}

function pidIsAlive(pid: number): boolean {
  try {
    process.kill(pid, 0);
    return true;
  } catch (error) {
    return errorCode(error) !== 'ESRCH';
  }
}

/** A lock record without a readable pid is only stealable once it is at least
 * this old: a fresher one may belong to a competing run mid-acquisition. */
const UNINITIALIZED_LOCK_GRACE_MS = 30_000;

function lockAgeMs(file: string): number | undefined {
  try {
    return Date.now() - fs.statSync(file).mtimeMs;
  } catch {
    return undefined;
  }
}

function acquireReportLock(reportDir: string): { file: string } {
  const file = path.join(reportDir, '.fallow-rush.lock');
  const record = JSON.stringify({
    pid: process.pid,
    startedAt: new Date().toISOString(),
  });
  for (let attempt = 0; attempt < 2; attempt += 1) {
    // Publish the lock record atomically: stage the complete record in a
    // private temp file, then hard-link it into place. `link(2)` fails with
    // EEXIST while the lock is held, and the lock file is never observable
    // half-initialized - a competing reader can never see it empty and
    // mistake a live acquisition for a stale record.
    const staging = path.join(
      reportDir,
      `.fallow-rush.lock.${process.pid}.${randomBytes(6).toString('hex')}.tmp`,
    );
    let created = false;
    try {
      fs.writeFileSync(staging, record, { flag: 'wx', mode: 0o600 });
      try {
        fs.linkSync(staging, file);
        created = true;
      } catch (error) {
        if (errorCode(error) !== 'EEXIST') throw error;
      }
    } finally {
      try {
        fs.unlinkSync(staging);
      } catch {
        // Best-effort staging cleanup; the lock itself is already published.
      }
    }
    if (created) return { file };

    const pid = lockPid(file);
    const age = lockAgeMs(file);
    if (pid === undefined && age !== undefined && age < UNINITIALIZED_LOCK_GRACE_MS) {
      throw new Error(
        `another fallow-rush run is acquiring the lock on report directory "${reportDir}" ` +
          '(lock record not yet initialized)',
      );
    }
    if (pid !== undefined && pidIsAlive(pid)) {
      throw new Error(
        `another fallow-rush run (pid ${pid}) is writing report directory "${reportDir}"`,
      );
    }
    if (attempt === 1) {
      throw new Error(`could not acquire fallow-rush report lock "${file}" after stale takeover`);
    }
    try {
      fs.unlinkSync(file);
    } catch (unlinkError) {
      if (errorCode(unlinkError) !== 'ENOENT') throw unlinkError;
    }
  }
  throw new Error(`could not acquire fallow-rush report lock "${file}"`);
}

function releaseReportLock(lock: { file: string }): void {
  try {
    fs.unlinkSync(lock.file);
  } catch (error) {
    if (errorCode(error) !== 'ENOENT') throw error;
  }
}

/**
 * Write the full report tree: monorepo.{json,md} + projects/<name>.{json,md}.
 * The projects/ directory is rebuilt from scratch so a narrowed run never
 * leaves stale files from a previous, wider run beside its own output -
 * guarded by {@link guardForeignProjectsDir} (never delete what we don't own)
 * and {@link guardScopeConflict} (never silently clobber a differently-scoped
 * report; closes issue #5). Every file is written atomically.
 */
export function writeReports(
  rollup: Rollup,
  reportDir: string,
  options: WriteReportsOptions = {},
): string[] {
  if (!options.explicitOut) reportDir = guardDefaultReportDir(reportDir);
  assertNoReportCollisions(rollup.projects.map((project) => project.project));
  fs.mkdirSync(reportDir, { recursive: true });
  const lock = acquireReportLock(reportDir);
  try {
    guardScopeConflict(rollup, reportDir, options);
    guardForeignProjectsDir(reportDir);

    const written: string[] = [];
    const projectsDir = path.join(reportDir, 'projects');
    fs.rmSync(projectsDir, { recursive: true, force: true });
    fs.mkdirSync(projectsDir, { recursive: true });

    const write = (file: string, content: string): void => {
      writeFileAtomic(file, content);
      written.push(file);
    };

    write(path.join(reportDir, 'monorepo.json'), `${JSON.stringify(rollup, null, 2)}\n`);
    write(path.join(reportDir, 'monorepo.md'), monorepoMarkdown(rollup));
    for (const project of rollup.projects) {
      const base = projectFileBase(project.project);
      write(path.join(projectsDir, `${base}.json`), `${JSON.stringify(project, null, 2)}\n`);
      write(path.join(projectsDir, `${base}.md`), projectMarkdown(rollup, project.project));
    }
    return written;
  } finally {
    releaseReportLock(lock);
  }
}
