import { describe, expect, it } from 'vitest';
import { mergeSplitBoms, missingShippedProjects, type WorkspaceProjectInfo } from './merge.js';
import type { CdxBom } from './types.js';

/** Shaped like real pnpm 11.11.0 --split output (observed in B0). */
function splitBom(
  rootName: string,
  rootVersion: string,
  components: Array<[string, string]>,
  dependsOn: string[],
): CdxBom {
  return {
    $schema: 'http://cyclonedx.org/schema/bom-1.6.schema.json',
    bomFormat: 'CycloneDX',
    specVersion: '1.6',
    serialNumber: 'urn:uuid:00000000-0000-4000-8000-000000000000',
    version: 1,
    metadata: {
      timestamp: '2026-07-11T00:00:00.000Z',
      tools: { components: [{ type: 'application', name: 'pnpm', version: '11.11.0' }] },
      component: {
        type: 'library',
        name: rootName,
        version: rootVersion,
        purl: `pkg:npm/${rootName}@${rootVersion}`,
        'bom-ref': `pkg:npm/${rootName}@${rootVersion}`,
        description: 'Temporary file generated by the Rush tool',
      },
    },
    components: components.map(([name, version]) => ({
      type: 'library',
      name,
      version,
      purl: `pkg:npm/${name}@${version}`,
      'bom-ref': `pkg:npm/${name}@${version}`,
    })),
    dependencies: [
      { ref: `pkg:npm/${rootName}@${rootVersion}`, dependsOn },
      ...components.map(([name, version]) => ({
        ref: `pkg:npm/${name}@${version}`,
        dependsOn: [],
      })),
    ],
  };
}

const projects: WorkspaceProjectInfo[] = [
  { name: 'web-app', version: '1.0.0', workspaceDependencies: ['lib-a', 'lib-b'] },
  { name: 'lib-a', version: '1.0.0', workspaceDependencies: [] },
  { name: 'lib-b', version: '1.0.0', workspaceDependencies: ['lib-a'] },
];

const splits = [
  splitBom(
    'web-app',
    '1.0.0',
    [
      ['ms', '2.1.3'],
      ['kleur', '4.1.5'],
    ],
    ['pkg:npm/ms@2.1.3', 'pkg:npm/kleur@4.1.5'],
  ),
  splitBom('lib-a', '1.0.0', [], []),
  splitBom('lib-b', '1.0.0', [], []),
];

describe('mergeSplitBoms', () => {
  it('keeps the deployed project as the root component', () => {
    const merged = mergeSplitBoms(splits, 'web-app', projects);
    expect(merged.metadata?.component?.name).toBe('web-app');
  });

  it('strips the rush temp description from the root component', () => {
    const merged = mergeSplitBoms(splits, 'web-app', projects);
    expect(merged.metadata?.component?.description).toBeUndefined();
  });

  it('adds non-main workspace projects as components, marked as such', () => {
    const merged = mergeSplitBoms(splits, 'web-app', projects);
    const names = merged.components?.map((c) => c.name);
    expect(names).toContain('lib-a');
    expect(names).toContain('lib-b');
    expect(names).not.toContain('web-app');
    const libA = merged.components?.find((c) => c.name === 'lib-a');
    expect(libA?.properties).toEqual([{ name: 'sbom-rush:workspace-project', value: 'true' }]);
  });

  it('keeps registry components with their hashes deduped by bom-ref', () => {
    const merged = mergeSplitBoms(splits, 'web-app', projects);
    expect(merged.components?.filter((c) => c.name === 'ms')).toHaveLength(1);
  });

  it('restores workspace dependency edges from the shipped manifests', () => {
    const merged = mergeSplitBoms(splits, 'web-app', projects);
    const root = merged.dependencies?.find((d) => d.ref === 'pkg:npm/web-app@1.0.0');
    expect(root?.dependsOn).toContain('pkg:npm/lib-a@1.0.0');
    expect(root?.dependsOn).toContain('pkg:npm/lib-b@1.0.0');
    expect(root?.dependsOn).toContain('pkg:npm/ms@2.1.3');
    const libB = merged.dependencies?.find((d) => d.ref === 'pkg:npm/lib-b@1.0.0');
    expect(libB?.dependsOn).toEqual(['pkg:npm/lib-a@1.0.0']);
  });

  it('is deterministic: components and dependencies are sorted', () => {
    const merged = mergeSplitBoms(splits, 'web-app', projects);
    const refs = (merged.components ?? []).map((c) => String(c['bom-ref']));
    expect(refs).toEqual([...refs].toSorted((a, b) => a.localeCompare(b)));
    const depRefs = (merged.dependencies ?? []).map((d) => d.ref);
    expect(depRefs).toEqual([...depRefs].toSorted((a, b) => a.localeCompare(b)));
  });

  it('throws when the deployed project has no split SBOM', () => {
    expect(() => mergeSplitBoms(splits.slice(1), 'web-app', projects)).toThrow(
      /no SBOM for the deployed project/,
    );
  });

  it('rejects a shipped split whose root version is missing', () => {
    const versionless = splitBom('lib-a', '1.0.0', [], []);
    delete versionless.metadata?.component?.version;

    expect(() =>
      mergeSplitBoms([splits[0]!, versionless, splits[2]!], 'web-app', projects),
    ).toThrow(/version skew.*lib-a.*1\.0\.0.*missing version/s);
  });
});

describe('missingShippedProjects (the rung acceptance gate)', () => {
  it('passes a complete merged SBOM', () => {
    const merged = mergeSplitBoms(splits, 'web-app', projects);
    expect(missingShippedProjects(merged, 'web-app', ['web-app', 'lib-a', 'lib-b'])).toEqual([]);
  });

  it('flags omitted workspace projects (the raw rung-2 gap)', () => {
    const raw = splits[0]!; // pnpm's un-merged SBOM for web-app alone
    expect(missingShippedProjects(raw, 'web-app', ['web-app', 'lib-a', 'lib-b'])).toEqual([
      'lib-a',
      'lib-b',
    ]);
  });

  it('flags a root component that is not the deployed project', () => {
    const wrongRoot = splitBom('rush-common', '0.0.0', [], []);
    expect(missingShippedProjects(wrongRoot, 'web-app', ['web-app'])).toEqual(['web-app']);
  });
});

describe('merge hardening (audit 2026-07-18)', () => {
  const shipped = [
    { name: 'web-app', version: '1.0.0', workspaceDependencies: ['lib-a'] },
    { name: 'lib-a', version: '1.0.0', workspaceDependencies: [] },
  ];

  function split(
    rootName: string,
    rootVersion: string,
    components: object[] = [],
    dependencies: object[] = [],
  ) {
    return {
      bomFormat: 'CycloneDX',
      specVersion: '1.6',
      version: 1,
      metadata: {
        component: {
          type: 'library',
          name: rootName,
          version: rootVersion,
          purl: `pkg:npm/${rootName}@${rootVersion}`,
          'bom-ref': `pkg:npm/${rootName}@${rootVersion}`,
        },
      },
      components,
      dependencies,
    } as never;
  }

  it('drops splits for projects outside the shipped closure (dev-dependency projects)', () => {
    // Real-repo repro (microsoft/rush-example): a devDependency toolchain
    // project gets a split via pnpm's filter traversal but never shipped.
    const merged = mergeSplitBoms(
      [
        split('web-app', '1.0.0'),
        split('lib-a', '1.0.0'),
        split(
          'build-tool',
          '9.9.9',
          [
            {
              type: 'library',
              name: 'colors',
              version: '1.4.0',
              purl: 'pkg:npm/colors@1.4.0',
              'bom-ref': 'pkg:npm/colors@1.4.0',
            },
          ],
          [{ ref: 'pkg:npm/build-tool@9.9.9', dependsOn: ['pkg:npm/colors@1.4.0'] }],
        ),
      ],
      'web-app',
      shipped,
    );
    const names = (merged.components ?? []).map((c) => c.name);
    expect(names).not.toContain('colors');
    expect(names).not.toContain('build-tool');
    const refs = new Set([
      merged.metadata?.component?.['bom-ref'],
      ...(merged.components ?? []).map((c) => c['bom-ref']),
    ]);
    for (const dep of merged.dependencies ?? []) {
      expect(refs.has(dep.ref), `dangling ref ${dep.ref}`).toBe(true);
      for (const d of dep.dependsOn ?? []) expect(refs.has(d), `dangling edge ${d}`).toBe(true);
    }
  });

  it('keeps the richer registry component on a purl collision, adding the workspace marker', () => {
    const registryLibA = {
      type: 'library',
      name: 'lib-a',
      version: '1.0.0',
      purl: 'pkg:npm/lib-a@1.0.0',
      'bom-ref': 'pkg:npm/lib-a@1.0.0',
      hashes: [{ alg: 'SHA-512', content: 'abc' }],
      licenses: [{ license: { id: 'MIT' } }],
    };
    const merged = mergeSplitBoms(
      [split('web-app', '1.0.0', [registryLibA]), split('lib-a', '1.0.0')],
      'web-app',
      shipped,
    );
    const libA = (merged.components ?? []).find((c) => c.name === 'lib-a');
    expect(libA?.hashes).toBeDefined();
    expect(libA?.licenses).toBeDefined();
    expect(libA?.properties).toContainEqual({ name: 'sbom-rush:workspace-project', value: 'true' });
  });

  it('refuses on deploy-vs-workspace version skew instead of shipping a wrong SBOM', () => {
    expect(() =>
      mergeSplitBoms([split('web-app', '2.0.0'), split('lib-a', '1.0.0')], 'web-app', shipped),
    ).toThrow(/version skew.*web-app.*1\.0\.0.*2\.0\.0.*rush deploy/s);
  });
});
