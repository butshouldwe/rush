import type { CdxBom, CdxComponent, CdxDependency } from './types.js';

/** What the merge needs to know about one shipped workspace project. */
export interface WorkspaceProjectInfo {
  name: string;
  version: string;
  /** Names of other shipped workspace projects this one depends on. */
  workspaceDependencies: string[];
}

const RUSH_TEMP_DESCRIPTION = 'Temporary file generated by the Rush tool';
const WORKSPACE_PROPERTY = { name: 'sbom-rush:workspace-project', value: 'true' } as const;

function purlOf(p: WorkspaceProjectInfo): string {
  return `pkg:npm/${p.name}@${p.version}`;
}

function refOf(component: CdxComponent): string {
  return component['bom-ref'] ?? component.purl ?? `${component.name}@${component.version}`;
}

function withWorkspaceProperty(component: CdxComponent): CdxComponent {
  const properties = component.properties ?? [];
  if (properties.some((p) => p.name === WORKSPACE_PROPERTY.name)) return component;
  return { ...component, properties: [...properties, WORKSPACE_PROPERTY] };
}

/**
 * Merge pnpm's per-package split SBOMs into one SBOM for the deployed
 * artifact.
 *
 * pnpm's split output (one SBOM per workspace package in the closure) has
 * three gaps, all verified empirically against pnpm 11.11.0:
 *   - the `--filter "main..."` selection traverses dev workspace deps, so
 *     splits exist for projects that never shipped — they must be dropped or
 *     phantom components/edges leak into the SBOM (verified against
 *     microsoft/rush-example: a devDependency toolchain project appeared as a
 *     dangling ref and its deps as phantom components)
 *   - workspace packages never appear as components in each other's SBOMs
 *   - workspace dependency edges are omitted from the dependency graph
 * The merge keeps only the shipped closure (per extractor-metadata.json) and
 * restores workspace components/edges from the projects' real manifests.
 */
export function mergeSplitBoms(
  splits: CdxBom[],
  mainProjectName: string,
  shippedProjects: WorkspaceProjectInfo[],
): CdxBom {
  const projectByName = new Map(shippedProjects.map((p) => [p.name, p]));
  const shippedNames = new Set([mainProjectName, ...projectByName.keys()]);

  const byRoot = new Map<string, CdxBom>();
  for (const bom of splits) {
    const rootName = bom.metadata?.component?.name;
    if (rootName) byRoot.set(rootName, bom);
  }

  const main = byRoot.get(mainProjectName);
  if (!main) {
    throw new Error(
      `pnpm sbom --split produced no SBOM for the deployed project "${mainProjectName}" ` +
        `(got: ${[...byRoot.keys()].join(', ') || 'none'}).`,
    );
  }

  const missingSplits = shippedProjects
    .map((project) => project.name)
    .filter((name) => !byRoot.has(name));
  if (missingSplits.length > 0) {
    throw new Error(
      `pnpm sbom --split produced no SBOM for shipped project(s): ${missingSplits.join(', ')} ` +
        `(got: ${[...byRoot.keys()].join(', ') || 'none'}).`,
    );
  }

  // Only splits for shipped projects participate; the rest are dev-closure
  // artifacts of pnpm's filter traversal.
  const shippedSplits = [...byRoot.entries()]
    .filter(([name]) => shippedNames.has(name))
    .map(([, bom]) => bom);

  // The workspace lockfile must describe the same versions the deploy folder
  // shipped — otherwise the SBOM would describe a build that never deployed.
  for (const project of shippedProjects) {
    const split = byRoot.get(project.name);
    const splitVersion = split?.metadata?.component?.version;
    if (splitVersion !== project.version) {
      throw new Error(
        `version skew for workspace project "${project.name}": the deploy folder shipped ` +
          `${project.version} but the workspace lockfile emitted ${splitVersion ?? '<missing version>'} — ` +
          `re-run \`rush deploy\` so the deploy output matches the current workspace.`,
      );
    }
  }

  // Components: union of every shipped split's components, deduped by
  // bom-ref, plus one component per non-main shipped workspace project.
  // On a purl collision (a shipped project also present as a registry
  // component) the richer registry entry is KEPT — hashes/licenses must not
  // be clobbered — and just gains the workspace-project marker.
  const components = new Map<string, CdxComponent>();
  for (const bom of shippedSplits) {
    for (const component of bom.components ?? []) {
      const ref = refOf(component);
      if (!components.has(ref)) components.set(ref, component);
    }
  }
  for (const project of shippedProjects) {
    if (project.name === mainProjectName) continue;
    const ref = purlOf(project);
    const existing = components.get(ref);
    components.set(
      ref,
      withWorkspaceProperty(
        existing ?? {
          type: 'library',
          name: project.name,
          version: project.version,
          purl: ref,
          'bom-ref': ref,
        },
      ),
    );
  }

  const mainComponent: CdxComponent = { ...(main.metadata?.component as CdxComponent) };
  if (mainComponent.description === RUSH_TEMP_DESCRIPTION) delete mainComponent.description;
  const mainRef = refOf(mainComponent);

  // Dependency graph: union by ref across shipped splits, then restore
  // workspace edges. Refs must resolve — a dependency entry or edge pointing
  // at nothing (typically dev-closure residue) is pruned rather than shipped.
  const dependencies = new Map<string, Set<string>>();
  for (const bom of shippedSplits) {
    for (const dep of bom.dependencies ?? []) {
      const existing = dependencies.get(dep.ref) ?? new Set<string>();
      for (const d of dep.dependsOn ?? []) existing.add(d);
      dependencies.set(dep.ref, existing);
    }
  }
  // pnpm emits each split's root under its own purl-style ref
  // (pkg:npm/<name>@<version>); workspace edges connect those refs.
  for (const project of shippedProjects) {
    const ref = purlOf(project);
    const dependsOn = dependencies.get(ref) ?? new Set<string>();
    for (const depName of project.workspaceDependencies) {
      const target = projectByName.get(depName);
      if (target) dependsOn.add(purlOf(target));
    }
    dependencies.set(ref, dependsOn);
  }

  const knownRefs = new Set([mainRef, ...components.keys()]);
  const sortedComponents = [...components.values()].toSorted((a, b) =>
    String(a['bom-ref'] ?? a.name).localeCompare(String(b['bom-ref'] ?? b.name)),
  );
  const sortedDependencies: CdxDependency[] = [...dependencies.entries()]
    .filter(([ref]) => knownRefs.has(ref))
    .toSorted(([a], [b]) => a.localeCompare(b))
    .map(([ref, dependsOn]) => ({
      ref,
      dependsOn: [...dependsOn].filter((d) => knownRefs.has(d)).toSorted(),
    }));

  return {
    ...main,
    metadata: { ...main.metadata, component: mainComponent },
    components: sortedComponents,
    dependencies: sortedDependencies,
  };
}

/**
 * The uniform rung acceptance gate: every project rush actually shipped
 * (per extractor-metadata.json) must appear in the SBOM — the main project as
 * the root component, every other one as a component. Returns the list of
 * missing project names (empty = pass).
 */
export function missingShippedProjects(
  bom: CdxBom,
  mainProjectName: string,
  shippedProjectNames: string[],
): string[] {
  const rootName = bom.metadata?.component?.name;
  const componentNames = new Set((bom.components ?? []).map((c) => c.name));
  return shippedProjectNames.filter((name) =>
    name === mainProjectName ? rootName !== name : !componentNames.has(name),
  );
}
